
import streamlit as st
import pandas as pd
import joblib
import requests
from io import BytesIO


# --------------------------------------------------
# PAGE CONFIGURATION
# --------------------------------------------------

st.set_page_config(
    page_title="House Price Predictor",
    page_icon="🏠",
    layout="centered"
)


# --------------------------------------------------
# LOAD TRAINED MODEL
# --------------------------------------------------

model_url = "https://huggingface.co/KizzaJordan84/house-price-prediction-model/resolve/main/house_price_model.pkl"

response = requests.get(model_url)
response.raise_for_status()

model = joblib.load(BytesIO(response.content))


# --------------------------------------------------
# APPLICATION TITLE
# --------------------------------------------------

st.title("🏠 House Price Predictor")

st.write(
    """
    Enter the characteristics of a house below and the
    machine-learning model will estimate its median house value.
    """
)

st.info(
    "This application uses a Random Forest machine-learning model "
    "trained on housing data."
)


# --------------------------------------------------
# HOUSE LOCATION
# --------------------------------------------------

st.header("📍 Location")

longitude = st.number_input(
    "Longitude",
    value=-122.23,
    format="%.4f"
)

latitude = st.number_input(
    "Latitude",
    value=37.88,
    format="%.4f"
)

ocean_proximity = st.selectbox(
    "Ocean Proximity",
    [
        "<1H OCEAN",
        "INLAND",
        "NEAR BAY",
        "NEAR OCEAN",
        "ISLAND"
    ]
)


# --------------------------------------------------
# HOUSE CHARACTERISTICS
# --------------------------------------------------

st.header("🏡 House Characteristics")

housing_median_age = st.number_input(
    "Housing Median Age (years)",
    min_value=1.0,
    value=30.0
)

total_rooms = st.number_input(
    "Total Rooms",
    min_value=1.0,
    value=2000.0
)

total_bedrooms = st.number_input(
    "Total Bedrooms",
    min_value=1.0,
    value=400.0
)


# --------------------------------------------------
# POPULATION INFORMATION
# --------------------------------------------------

st.header("👥 Household Information")

population = st.number_input(
    "Population",
    min_value=1.0,
    value=1000.0
)

households = st.number_input(
    "Households",
    min_value=1.0,
    value=300.0
)

median_income = st.number_input(
    "Median Income",
    min_value=0.1,
    value=4.0
)


# --------------------------------------------------
# PREDICTION
# --------------------------------------------------

st.divider()

if st.button(
    "🔮 Predict House Value",
    use_container_width=True
):

    input_data = pd.DataFrame({
        "longitude": [longitude],
        "latitude": [latitude],
        "housing_median_age": [housing_median_age],
        "total_rooms": [total_rooms],
        "total_bedrooms": [total_bedrooms],
        "population": [population],
        "households": [households],
        "median_income": [median_income],
        "ocean_proximity": [ocean_proximity]
    })

    prediction = model.predict(input_data)

    predicted_value = prediction[0]

    st.success(
        f"### Estimated House Value: ${predicted_value:,.0f}"
    )

    st.write(
        "The value above is an estimate generated by the "
        "machine-learning model."
    )


# --------------------------------------------------
# DISCLAIMER
# --------------------------------------------------

st.divider()

st.caption(
    "⚠️ Disclaimer: This prediction is for demonstration and "
    "educational purposes only. It should not be treated as "
    "an official property valuation or professional appraisal."
)

